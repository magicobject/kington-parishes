// Samples ground height along each leg of the journey (see
// src/journey.config.mjs) and writes src/journey-profile.json.
// Run with `npm run journey:profile`; needs the network (OpenTopoData's free
// public API, EU-DEM 25 m, no key — 100 points per request, 1 request a
// second). Not part of `npm run build`.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { CHURCHES } from '../src/churches.config.mjs';
import { JOURNEY } from '../src/journey.config.mjs';
import { legSamplePoints } from './ridge.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const stops = JOURNEY.map((slug) => {
  const c = CHURCHES.find((x) => x.slug === slug);
  if (!c) throw new Error(`journey: no church "${slug}" in churches.config.mjs`);
  return c;
});

const { points, stopIndexes } = legSamplePoints(stops);
const elevation = [];
for (let i = 0; i < points.length; i += 100) {
  if (i) await new Promise((r) => setTimeout(r, 1200));
  const chunk = points.slice(i, i + 100);
  const url = `https://api.opentopodata.org/v1/eudem25m?locations=${chunk.map((p) => `${p.lat.toFixed(6)},${p.lng.toFixed(6)}`).join('|')}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`elevation service answered ${res.status}`);
  const body = await res.json();
  if (body.status !== 'OK' || body.results.length !== chunk.length) throw new Error('elevation service returned an unexpected shape');
  for (const r of body.results) {
    if (typeof r.elevation !== 'number') throw new Error('elevation service returned no height for a point');
    elevation.push(Math.round(r.elevation));
  }
}

const profile = {
  note: 'Generated by scripts/generate-journey-profile.mjs — do not hand-edit. Heights in metres (EU-DEM 25 m via OpenTopoData); points are [metres along the journey, height].',
  stops: stops.map((c, i) => ({ slug: c.slug, lat: c.lat, lng: c.lng, index: stopIndexes[i] })),
  points: points.map((p, i) => [Math.round(p.x), elevation[i]]),
};
const pointLines = profile.points.map((p) => '  ' + JSON.stringify(p)).join(',\n');
const text = '{\n "note": ' + JSON.stringify(profile.note) + ',\n "stops": ' + JSON.stringify(profile.stops) + ',\n "points": [\n' + pointLines + '\n ]\n}\n';
writeFileSync(join(root, 'src/journey-profile.json'), text);
console.log(`wrote src/journey-profile.json (${points.length} points, ${stops.length} stops)`);
