// Samples ground height along each leg of the journey (see
// src/journey.config.mjs) and writes src/journey-profile.json.
// Run with `npm run journey:profile`; needs the network (Open-Meteo's free
// elevation service, ~90 m resolution, no key). Not part of `npm run build`.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { CHURCHES } from '../src/churches.config.mjs';
import { JOURNEY } from '../src/journey.config.mjs';
import { legSamplePoints } from './ridge.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const stops = JOURNEY.map((slug) => {
  const c = CHURCHES.find((x) => x.slug === slug);
  if (!c) throw new Error(`journey: no church "${slug}" in churches.config.mjs`);
  return c;
});

const points = legSamplePoints(stops);
const url = `https://api.open-meteo.com/v1/elevation?latitude=${points.map((p) => p.lat.toFixed(6))}&longitude=${points.map((p) => p.lng.toFixed(6))}`;
const res = await fetch(url);
if (!res.ok) throw new Error(`elevation service answered ${res.status}`);
const { elevation } = await res.json();
if (!Array.isArray(elevation) || elevation.length !== points.length) throw new Error('elevation service returned an unexpected shape');

const profile = {
  note: 'Generated by scripts/generate-journey-profile.mjs — do not hand-edit. Elevations in metres (Open-Meteo, ~90 m grid).',
  stops: stops.map((c) => ({ slug: c.slug, lat: c.lat, lng: c.lng })),
  points: points.map((p, i) => ({ x: Math.round(p.x), e: elevation[i] })),
};
writeFileSync(join(root, 'src/journey-profile.json'), JSON.stringify(profile, null, 1) + '\n');
console.log(`wrote src/journey-profile.json (${points.length} points, ${stops.length} stops)`);
