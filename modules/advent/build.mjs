// Escapes text for HTML text and attribute values. Braces are written as numeric entities
// too, so a later {{TOKEN}} pass over the finished page can never find a token in our output,
// and $ as well, because the host splices the page into its template with String#replace.
function escapeText(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
    .replace(/\$/g, '&#36;')
    .replace(/\{/g, '&#123;')
    .replace(/\}/g, '&#125;')
    .replace(/\u00A0/g, '&nbsp;');
}

const dayNumber = (day) => String(day).padStart(2, '0');

function banner(file, comment) {
  const lines = [
    'AUTO-GENERATED \u2014 DO NOT EDIT THIS FILE.',
    `Generated by modules/advent/build.mjs${file ? ` from ${file}` : ''} on every build.`,
    'Edit the source instead, then run `npm run build`.',
  ];
  return comment === 'block' ? `/* ${lines.join('\n   ')} */\n` : `${lines.map((line) => `// ${line}`).join('\n')}\n`;
}

// Writes only when the text differs, so an unchanged rebuild leaves every file alone.
function writeIfChanged(path, text) {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

const shortHash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 10);

