// The scene picture

const SCENE_COMMENT = '<!-- AUTO-GENERATED - DO NOT EDIT THIS FILE. Copied from the Advent module by the build. Edit the module scene file instead, then rebuild. -->\n';

// The calendar's backdrop: the site's own scene (a hand-made file in public/advent/, named by theme.scene) or,
// failing that, the module's plain hills. Either way it is checked like any other picture. Returns the address
// the page should use and, for the module's own scene, the file to write.
function checkScene(publicDir, theme) {
  if (theme.scene) {
    const full = join(publicDir, 'advent', theme.scene);
    let info = null;
    try {
      info = lstatSync(full);
    } catch {
      info = null;
    }
    if (!info) throw new Error(`scene: ${theme.scene} is named in the theme but is not in public/advent/`);
    if (info.isSymbolicLink() || !info.isFile()) throw new Error(`scene: ${theme.scene} is a link or not a file`);
    const problems = lintSvg(readFileSync(full, 'utf8'));
    if (problems.length > 0) throw new Error(`scene: ${theme.scene} refused: ${problems.join('; ')}`);
    return { url: `/advent/${theme.scene}`, output: null };
  }
  const text = readFileSync(join(MODULE_DIR, 'client', 'scene.svg'), 'utf8');
  const problems = lintSvg(text);
  if (problems.length > 0) throw new Error(`scene: the module's own scene is refused: ${problems.join('; ')}`);
  return { url: '/advent/scene-default.svg', output: ['advent/scene-default.svg', `${SCENE_COMMENT}${text}`] };
}

const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

function themeCss(theme) {
  const lines = COLOUR_NAMES.map((name) => `  --advent-${kebab(name)}: ${theme.colours[name].toLowerCase()};`);
  return `${banner('the theme in modules/advent/theme.mjs', 'block')}:root {\n${lines.join('\n')}\n}\n`;
}

