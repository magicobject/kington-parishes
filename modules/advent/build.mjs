// The page

function wholeNumber(value, where) {
  if (!Number.isInteger(value)) throw new Error(`season: ${where} must be a whole number`);
  return value;
}

// The settings both page scripts read, as data-* (name, value) pairs. Every number must be a whole number, and
// every value is escaped when it is written.
function settingsAttributes(ctx) {
  const { theme } = ctx;
  const { start, end, archiveUntil } = theme.season;
  const bonus = ctx.hasBonus && theme.bonus ? theme.bonus : null;
  const startMonth = wholeNumber(start.month, 'start.month');
  const startDay = wholeNumber(start.day, 'start.day');
  // A non-breaking space keeps the day number and the month together on one line.
  const opens = `The Advent calendar opens on ${startDay}\u00A0${MONTH_NAMES[startMonth - 1]}.`;
  const sceneUrl = typeof ctx.sceneUrl === 'string' && /^\/advent\/[a-z0-9-]+\.svg$/.test(ctx.sceneUrl) ? ctx.sceneUrl : null;
  return {
    opens,
    pairs: [
      ['data-advent', 'true'],
      ['data-slug', theme.slug],
      ['data-time-zone', theme.timeZone],
      ['data-site-name', theme.siteName],
      ['data-start-month', startMonth],
      ['data-start-day', startDay],
      ['data-end-month', wholeNumber(end.month, 'end.month')],
      ['data-end-day', wholeNumber(end.day, 'end.day')],
      ...(archiveUntil
        ? [['data-archive-month', wholeNumber(archiveUntil.month, 'archiveUntil.month')], ['data-archive-day', wholeNumber(archiveUntil.day, 'archiveUntil.day')]]
        : []),
      ['data-preview', theme.previewEnabled === true],
      ['data-enabled', theme.adventEnabled === true],
      ['data-go-live', theme.goLive === true],
      ['data-day-count', DAY_COUNT],
      ...(bonus
        ? [['data-bonus-month', wholeNumber(bonus.on.month, 'bonus.on.month')], ['data-bonus-day', wholeNumber(bonus.on.day, 'bonus.on.day')], ['data-bonus-label', bonus.label]]
        : []),
      ...(sceneUrl ? [['data-scene', sceneUrl]] : []),
      ['data-month-name', MONTH_NAMES[startMonth - 1]],
      ['data-opens-text', opens],
    ],
  };
}

const attributeText = (pairs) => pairs.map(([name, value]) => `${name}="${escapeText(value)}"`).join(' ');

/**
 * Replaces {{ADVENT}} with the calendar's markup: MARKUP ONLY, nothing from the days, no script,
 * no style attribute, no event handler. The page must supply its own h1; this adds h2s only.
 * Run it before the host adds heading ids. Pass ctx = buildAdvent(...).tokenContext.
 */
export function renderAdventToken(html, ctx) {
  if (!html.includes(TOKEN)) return html;
  const { opens, pairs } = settingsAttributes(ctx);
  const heading = escapeText(`${ctx.theme.siteName} Advent calendar`);

  const markup = `<section class="advent" ${attributeText(pairs)}>
  <div class="advent-notice" data-advent-notice role="status" hidden>
    <p data-advent-notice-text></p>
  </div>
  <div class="advent-calm" data-advent-calm>
    <h2>${heading}</h2>
    <p data-advent-calm-text>${escapeText(opens)}</p>
  </div>
  <div class="advent-live" data-advent-live hidden>
    <h2 data-advent-heading>${heading}</h2>
    <p class="advent-status" data-advent-status></p>
    <p class="advent-primary"><button type="button" class="advent-pill" data-advent-primary hidden>${escapeText("Open today's door")}</button></p>
    <ul class="advent-doors" data-advent-doors></ul>
    <div class="advent-scene" data-advent-scene aria-hidden="true"></div>
  </div>
  <noscript><p>The Advent calendar needs JavaScript to open its doors. Please switch JavaScript on and reload this page.</p></noscript>
</section>`;
  return html.split(TOKEN).join(markup);
}

/**
 * Replaces {{ADVENT_TEASER}} with the home-page banner's placeholder: ONE empty, hidden container carrying the
 * settings as data attributes, and the tag for the small banner script. No text, heading, link or image: the
 * script builds all of that, and only when the effective date is inside the season (live or archive). The two
 * stylesheet addresses are carried as data so the script can add them then; a visitor outside the season
 * downloads the script and nothing else.
 */
export function renderAdventTeaserToken(html, ctx) {
  if (!html.includes(TEASER_TOKEN)) return html;
  const { pairs } = settingsAttributes(ctx);
  const css = [['data-theme-css', ctx.themeCssUrl], ['data-teaser-css', ctx.teaserCssUrl]]
    .filter(([, value]) => typeof value === 'string' && /^\/css\/advent-[a-z]+\.css\?v=[0-9a-f]{10}$/.test(value));
  const attributes = attributeText([...pairs.filter(([name]) => name !== 'data-opens-text'), ...css]);
  const markup = `<div class="advent-teaser" data-advent-teaser ${attributes} hidden></div>\n<script type="module" src="/js/advent-teaser.js"></script>`;
  return html.split(TEASER_TOKEN).join(markup);
}

/**
 * The calendar page's entry for the host's page list. While theme.publicListing is false the page
 * is unlisted (kept out of the sitemap and search) and carries noindex; flipping publicListing to
 * true lists it and drops the noindex, with no other change.
 */
export function adventPageEntry(theme) {
  const checked = validateTheme(theme);
  const name = escapeText(checked.siteName);
  const entry = {
    slug: checked.slug,
    title: `Advent \u2014 ${name}`,
    description: `The ${name} Advent calendar.`,
    active: null,
    header: true,
    safeguardStrip: false,
    headHtml: [
      '<link rel="stylesheet" href="/css/advent-theme.css">',
      '<link rel="stylesheet" href="/css/advent.css">',
      '<script type="module" src="/js/advent.js"></script>',
    ].join('\n'),
    unlisted: !checked.publicListing,
  };
  if (!checked.publicListing) entry.robots = 'noindex, nofollow';
  return entry;
}

/** The draw weight of a picture (see drawCost), or null if the picture is refused for another reason first. */
export function svgDrawWeight(text) {
  const stats = {};
  const problems = lintSvg(text, stats);
  return problems.length > 0 && stats.weight === undefined ? null : stats.weight;
}
