// The browser runs the very same date.mjs and preview.mjs as the unit tests: the build copies
// them to js/advent/ (as .js, so every server sends a script type) and rewrites the import
// lines to point at those copies, with a content hash so a changed copy is never served stale.
export function rewriteImports(text, replacements, file) {
  // Fail closed: the only import allowed is a whole-line static import of a known file. Any other use of
  // the word (a bare one, a dynamic one, import.meta, or one inside a comment) or any export-from is refused.
  const statement = /^(import\s*\{[^}\n]*\}\s*from\s*)(['"])([^'"\n]+)\2[ \t]*;?[ \t]*$/gm;
  const used = new Set();
  let recognised = 0;
  const out = text.replace(statement, (whole, head, quote, specifier) => {
    if (!(specifier in replacements)) throw new Error(`${file}: only the known imports are allowed, not ${specifier}`);
    used.add(specifier);
    recognised += 1;
    return `${head}'${replacements[specifier]}';`;
  });
  if ((text.match(/\bimport\b/g) ?? []).length !== recognised) {
    throw new Error(`${file}: contains an import that is not a plain static import of a known file`);
  }
  if (/\bexport\s*(?:\*|\{[^}]*\})\s*from\b/.test(text)) throw new Error(`${file}: re-exporting from another file is not allowed`);
  for (const specifier of Object.keys(replacements)) {
    if (!used.has(specifier)) throw new Error(`${file}: expected the known import ${specifier}`);
  }
  return out;
}

function clientFiles() {
  const read = (path) => readFileSync(join(MODULE_DIR, path), 'utf8');
  const copy = (name, replacements = {}) => rewriteImports(`${banner(`modules/advent/${name}`)}${read(name)}`, replacements, name);
  const dateText = copy('date.mjs');
  const dayText = copy('day.mjs');
  const dateUrl = `./date.js?v=${shortHash(dateText)}`;
  const previewText = copy('preview.mjs', { './date.mjs': dateUrl });
  const logicText = copy('logic.mjs', { './date.mjs': dateUrl, './day.mjs': `./day.js?v=${shortHash(dayText)}` });
  // The two page scripts import the same three files, one folder up from the copies.
  const fromPage = {
    '../date.mjs': `./advent/date.js?v=${shortHash(dateText)}`,
    '../preview.mjs': `./advent/preview.js?v=${shortHash(previewText)}`,
    '../logic.mjs': `./advent/logic.js?v=${shortHash(logicText)}`,
  };
  const css = (name) => `${banner(`modules/advent/${name}`, 'block')}${read(name)}`;
  return [
    ['js/advent/date.js', dateText],
    ['js/advent/day.js', dayText],
    ['js/advent/preview.js', previewText],
    ['js/advent/logic.js', logicText],
    ['js/advent.js', copy('client/advent.js', fromPage)],
    ['js/advent-teaser.js', copy('client/advent-teaser.js', fromPage)],
    ['css/advent.css', css('client/advent.css')],
    ['css/advent-teaser.css', css('client/advent-teaser.css')],
  ];
}

