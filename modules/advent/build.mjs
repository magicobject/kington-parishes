// The build

/**
 * Checks everything, then writes the generated files into publicDir.
 * Returns { theme, content, pageUrl, artPresent, files, tokenContext } where theme and content
 * are the validators' checked copies and tokenContext is what renderAdventToken needs.
 */
export function buildAdvent({ theme, content, publicDir, siteUrl, pageNames } = {}) {
  const checkedTheme = validateTheme(theme);
  const checkedContent = validateContent(content);
  if (typeof siteUrl !== 'string' || !/^https:\/\/[^\s/]+$/.test(siteUrl)) {
    throw new Error('siteUrl must be an https address with no path, like https://example.org');
  }
  if (!Array.isArray(pageNames) || pageNames.includes(checkedTheme.slug)) {
    throw new Error(`the theme's slug "${checkedTheme.slug}" is already used by another page`);
  }
  if (typeof publicDir !== 'string' || publicDir === '') throw new Error('publicDir is required');

  const bonusEntry = checkedContent.bonus ?? null;
  if (bonusEntry && !checkedTheme.bonus) throw new Error('the content has a bonus day but the theme has no bonus: add "bonus" to the theme');
  const allDays = bonusEntry ? [...checkedContent.days, bonusEntry] : checkedContent.days;
  const artPresent = checkArt(publicDir, allDays, checkedTheme.artRequired, Boolean(bonusEntry));

  const outputs = [];
  for (const entry of allDays) {
    const file = dayFile(entry, artPresent.includes(entry.art));
    validateDayFile(file, entry.day);
    outputs.push([`advent/day-${dayNumber(entry.day)}.json`, `${JSON.stringify(file, null, 2)}\n`]);
  }
  outputs.push(['css/advent-theme.css', themeCss(checkedTheme)]);
  outputs.push(...clientFiles());

  for (const [path, text] of outputs) writeIfChanged(join(publicDir, path), text);

  return {
    theme: checkedTheme,
    content: checkedContent,
    pageUrl: `${siteUrl}/${checkedTheme.slug}.html`,
    artPresent,
    files: outputs.map(([path]) => path),
    tokenContext: { theme: checkedTheme, hasBonus: Boolean(bonusEntry) },
  };
}

// ---------------------------------------------------------------------------
// The page

function wholeNumber(value, where) {
  if (!Number.isInteger(value)) throw new Error(`season: ${where} must be a whole number`);
  return value;
}

/**
 * Replaces {{ADVENT}} with the calendar's markup: MARKUP ONLY, nothing from the days, no script,
 * no style attribute, no event handler. The page must supply its own h1; this adds h2s only.
 * Run it before the host adds heading ids. Pass ctx = buildAdvent(...).tokenContext.
 */
export function renderAdventToken(html, ctx) {
  if (!html.includes(TOKEN)) return html;
  const { theme } = ctx;
  const { start, end, archiveUntil } = theme.season;
  const bonus = ctx.hasBonus && theme.bonus ? theme.bonus : null;
  const startMonth = wholeNumber(start.month, 'start.month');
  const startDay = wholeNumber(start.day, 'start.day');
  // A non-breaking space keeps the day number and the month together on one line.
  const label = `${startDay}\u00A0${MONTH_NAMES[startMonth - 1]}`;
  const opens = `The Advent calendar opens on ${label}.`;
  const heading = escapeText(`${theme.siteName} Advent calendar`);
  const data = [
    ['data-advent', 'true'],
    ['data-slug', theme.slug],
    ['data-time-zone', theme.timeZone],
    ['data-start-month', startMonth],
    ['data-start-day', startDay],
    ['data-end-month', wholeNumber(end.month, 'end.month')],
    ['data-end-day', wholeNumber(end.day, 'end.day')],
    ...(archiveUntil
      ? [['data-archive-month', wholeNumber(archiveUntil.month, 'archiveUntil.month')], ['data-archive-day', wholeNumber(archiveUntil.day, 'archiveUntil.day')]]
      : []),
    ['data-preview', theme.previewEnabled === true],
    ['data-enabled', theme.adventEnabled === true],
    ['data-day-count', DAY_COUNT],
    ...(bonus
      ? [['data-bonus-month', wholeNumber(bonus.on.month, 'bonus.on.month')], ['data-bonus-day', wholeNumber(bonus.on.day, 'bonus.on.day')], ['data-bonus-label', bonus.label]]
      : []),
    ['data-month-name', MONTH_NAMES[startMonth - 1]],
    ['data-opens-text', opens],
  ].map(([name, value]) => `${name}="${escapeText(value)}"`).join(' ');

  const markup = `<section class="advent" ${data}>
  <div class="advent-notice" data-advent-notice hidden>
    <p data-advent-notice-text></p>
  </div>
  <div class="advent-calm" data-advent-calm>
    <h2>${heading}</h2>
    <p data-advent-calm-text>${escapeText(opens)}</p>
  </div>
  <div class="advent-live" data-advent-live hidden>
    <h2>${heading}</h2>
    <ul class="advent-doors" data-advent-doors></ul>
  </div>
  <noscript><p>The Advent calendar needs JavaScript to open its doors. Please switch JavaScript on and reload this page.</p></noscript>
</section>`;
  return html.split(TOKEN).join(markup);
}

/**
 * The calendar page's entry for the host's page list. While theme.publicListing is false the page
 * is unlisted (kept out of the sitemap and search) and carries noindex; flipping publicListing to
 * true lists it and drops the noindex, with no other change.
 */
export function adventPageEntry(theme) {
  const checked = validateTheme(theme);
  const name = escapeText(checked.siteName);
  const entry = {
    slug: checked.slug,
    title: `Advent \u2014 ${name}`,
    description: `The ${name} Advent calendar.`,
    active: null,
    header: true,
    safeguardStrip: false,
    headHtml: [
      '<link rel="stylesheet" href="/css/advent-theme.css">',
      '<link rel="stylesheet" href="/css/advent.css">',
      '<script type="module" src="/js/advent.js"></script>',
    ].join('\n'),
    unlisted: !checked.publicListing,
  };
  if (!checked.publicListing) entry.robots = 'noindex, nofollow';
  return entry;
}
