// Build step for the Advent calendar. Generic: the host site passes everything in
// ({theme, content, publicDir, siteUrl, pageNames}) and this file never reads the
// host's own files. It may import only from this folder and from Node itself.
//
// What it does, in order, and nothing is written unless every check passes:
//   1. checks the theme and the content with the validators, and uses the COPIES they return
//   2. checks the pictures in <publicDir>/advent/art (see lintSvg, artFilePath)
//   3. writes, all from that checked data:
//        advent/day-01.json ... day-25.json   one plain-text file per day (validated again)
//        css/advent-theme.css                 the theme's colours as --advent-* variables
//        css/advent.css, js/advent.js         copied from client/ (hand-maintained)
//        js/advent/date.js, js/advent/preview.js   copies of date.mjs and preview.mjs, so the
//                                             browser runs the very same date logic the tests do
// Every generated file starts with an AUTO-GENERATED banner (JSON cannot carry one) and is
// written the same way every time (stable key order, LF, one trailing newline), so a rebuild
// only changes a file when its source changed.
//
// Also exported for the host: renderAdventToken (the {{ADVENT}} markup) and adventPageEntry
// (the page's entry for the host's page list).
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COLOUR_NAMES, DAY_COUNT, artPathIsSafe, validateContent, validateDay, validateTheme } from './schema.mjs';

const MODULE_DIR = dirname(fileURLToPath(import.meta.url));
const MONTH_NAMES = [
  'January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December',
];
const MAX_SVG_BYTES = 100 * 1024;
const TOKEN = '{{ADVENT}}';

// ---------------------------------------------------------------------------
// Text helpers

// Escapes text for HTML text and attribute values. Braces are written as numeric entities
// too, so a later {{TOKEN}} pass over the finished page can never find a token in our output,
// and $ as well, because the host splices the page into its template with String#replace.
function escapeText(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
    .replace(/\$/g, '&#36;')
    .replace(/\{/g, '&#123;')
    .replace(/\}/g, '&#125;');
}

const dayNumber = (day) => String(day).padStart(2, '0');

function banner(file, comment) {
  const lines = [
    'AUTO-GENERATED — DO NOT EDIT THIS FILE.',
    `Generated by modules/advent/build.mjs${file ? ` from ${file}` : ''} on every build.`,
    'Edit the source instead, then run `npm run build`.',
  ];
  return comment === 'block' ? `/* ${lines.join('\n   ')} */\n` : `${lines.map((line) => `// ${line}`).join('\n')}\n`;
}

// Writes only when the text differs, so an unchanged rebuild leaves every file alone.
function writeIfChanged(path, text) {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

const shortHash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 10);

// ---------------------------------------------------------------------------
// Pictures

/**
 * Problems found in a picture, as a list of plain sentences (empty list = clean). A picture
 * may be shapes, gradients and internal #links only: no scripts, no handlers, no other
 * elements that can load or run anything, no link that leaves the file.
 */
export function lintSvg(text) {
  if (typeof text !== 'string') return ['the picture is not text'];
  const problems = [];
  if (Buffer.byteLength(text, 'utf8') > MAX_SVG_BYTES) problems.push('larger than 100 KB');
  if (!/<svg[\s>]/i.test(text) || !/<\/svg\s*>\s*$/i.test(text)) problems.push('is not a complete <svg> picture');

  const forbidden = [
    [/<\s*script/i, 'contains a script element'],
    [/<\s*foreignObject/i, 'contains a foreignObject element'],
    [/<\s*image[\s/>]/i, 'contains an image element'],
    [/<\s*(?:iframe|embed|object|audio|video|link|meta|base|canvas)[\s/>]/i, 'contains an element that can load content'],
    [/[\s"'/]on[a-z]+\s*=/i, 'contains an event handler attribute'],
    [/[\s"':]src\s*=/i, 'contains a src attribute'],
    [/attributeName\s*=\s*["']?\s*(?:xlink:)?href/i, 'animates a link'],
    [/@import/i, 'contains @import'],
    [/url\(\s*(?!["']?#)/i, 'contains a url() that is not an internal #link'],
    [/javascript\s*:/i, 'contains a javascript: address'],
    [/(?<![\w-])data\s*:/i,'contains a data: address'],
    [/<!ENTITY/i, 'declares an entity'],
    [/<!DOCTYPE[^>]*\[/i, 'has a DOCTYPE with declarations'],
    [/<\?xml-stylesheet/i, 'links an external stylesheet'],
  ];
  for (const [pattern, message] of forbidden) if (pattern.test(text)) problems.push(message);

  const hrefs = /(?:^|[\s"'/<])(?:xlink:)?href\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]*))/gi;
  for (const match of text.matchAll(hrefs)) {
    const value = match[1] ?? match[2] ?? match[3] ?? '';
    if (!value.startsWith('#')) problems.push('has a link that does not start with #');
  }
  return [...new Set(problems)];
}

/** The full path of one picture, refusing any name that is not a plain file name inside artDir. */
export function artFilePath(artDir, name) {
  if (!artPathIsSafe(name)) throw new Error(`art: "${String(name).slice(0, 40)}" is not a plain picture file name`);
  const root = resolve(artDir);
  const full = resolve(root, name);
  if (!full.startsWith(root + sep)) throw new Error(`art: "${name}" is outside the art folder`);
  return full;
}

// Looks at every picture. Returns the names that exist; throws one error listing every problem.
function checkArt(publicDir, days, required) {
  const artDir = join(publicDir, 'advent', 'art');
  const problems = [];
  const present = [];
  const named = new Set(days.map((entry) => entry.art));

  for (const name of named) {
    const full = artFilePath(artDir, name);
    if (!existsSync(full)) {
      if (required) problems.push(`${name}: missing (artRequired is on)`);
      continue;
    }
    present.push(name);
  }
  const stray = existsSync(artDir)
    ? readdirSync(artDir).filter((name) => /\.svg$/i.test(name) && !named.has(name))
    : [];
  for (const name of [...present, ...stray]) {
    if (stray.includes(name) && !artPathIsSafe(name)) {
      problems.push(`${name}: not a plain picture file name`);
      continue;
    }
    const full = join(artDir, name);
    if (lstatSync(full).isSymbolicLink()) {
      problems.push(`${name}: is a link, not a file`);
      continue;
    }
    for (const problem of lintSvg(readFileSync(full, 'utf8'))) problems.push(`${name}: ${problem}`);
  }
  if (problems.length > 0) throw new Error(`Advent pictures refused:\n  ${problems.join('\n  ')}`);
  return present;
}

// ---------------------------------------------------------------------------
// Day files

const DAY_FILE_ORDER = ['day', 'title', 'ref', 'paragraphs', 'wonder', 'activity', 'prayer', 'alt', 'hidden', 'translation', 'credit', 'art'];

function dayFile(entry, hasArt) {
  const file = {};
  for (const key of DAY_FILE_ORDER) {
    if (key === 'art' && !hasArt) continue;
    if (key in entry) file[key] = entry[key];
  }
  return file;
}

/** Throws unless a generated day file has exactly the right keys, in order, and valid text. */
export function validateDayFile(file, expectedDay) {
  if (file === null || typeof file !== 'object' || Array.isArray(file)) throw new Error('day file: must be an object');
  const keys = Object.keys(file);
  for (const key of keys) {
    if (!DAY_FILE_ORDER.includes(key)) throw new Error(`day file: unknown key "${key.slice(0, 40)}"`);
  }
  const expectedOrder = DAY_FILE_ORDER.filter((key) => key in file);
  if (keys.join() !== expectedOrder.join()) throw new Error('day file: keys are not in the fixed order');
  if (file.day !== expectedDay) throw new Error(`day file: "day" should be ${expectedDay}`);
  // validateDay wants an art name; a file without a picture gets a stand-in just for the check.
  validateDay({ ...file, art: file.art ?? 'day-01.svg' }, expectedDay - 1);
}

// ---------------------------------------------------------------------------
// Client files

// The browser runs the very same date.mjs and preview.mjs as the unit tests: the build copies
// them to js/advent/ (as .js, so every server sends a script type) and rewrites the import
// lines to point at those copies, with a content hash so a changed copy is never served stale.
function rewriteImports(text, replacements, file) {
  const used = new Set();
  const out = text.replace(/(\bfrom\s*)(['"])([^'"]+)\2/g, (whole, from, quote, specifier) => {
    if (!(specifier in replacements)) throw new Error(`${file}: only the known imports are allowed, not ${specifier}`);
    used.add(specifier);
    return `${from}'${replacements[specifier]}'`;
  });
  for (const specifier of Object.keys(replacements)) {
    if (!used.has(specifier)) throw new Error(`${file}: expected the known import ${specifier}`);
  }
  return out;
}

function clientFiles() {
  const read = (path) => readFileSync(join(MODULE_DIR, path), 'utf8');
  const dateText = `${banner('modules/advent/date.mjs')}${read('date.mjs')}`;
  const dateHash = shortHash(dateText);
  const previewText = rewriteImports(
    `${banner('modules/advent/preview.mjs')}${read('preview.mjs')}`,
    { './date.mjs': `./date.js?v=${dateHash}` },
    'preview.mjs',
  );
  const previewHash = shortHash(previewText);
  const clientText = rewriteImports(
    `${banner('modules/advent/client/advent.js')}${read('client/advent.js')}`,
    { '../date.mjs': `./advent/date.js?v=${dateHash}`, '../preview.mjs': `./advent/preview.js?v=${previewHash}` },
    'client/advent.js',
  );
  return [
    ['js/advent/date.js', dateText],
    ['js/advent/preview.js', previewText],
    ['js/advent.js', clientText],
    ['css/advent.css', `${banner('modules/advent/client/advent.css', 'block')}${read('client/advent.css')}`],
  ];
}

const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

function themeCss(theme) {
  const lines = COLOUR_NAMES.map((name) => `  --advent-${kebab(name)}: ${theme.colours[name].toLowerCase()};`);
  return `${banner('the theme in modules/advent/theme.mjs', 'block')}:root {\n${lines.join('\n')}\n}\n`;
}

// ---------------------------------------------------------------------------
// The build

/**
 * Checks everything, then writes the generated files into publicDir.
 * Returns { theme, content, pageUrl, artPresent, files, tokenContext } where theme and content
 * are the validators' checked copies and tokenContext is what renderAdventToken needs.
 */
export function buildAdvent({ theme, content, publicDir, siteUrl, pageNames } = {}) {
  const checkedTheme = validateTheme(theme);
  const checkedContent = validateContent(content);
  if (typeof siteUrl !== 'string' || !/^https:\/\/[^\s/]+$/.test(siteUrl)) {
    throw new Error('siteUrl must be an https address with no path, like https://example.org');
  }
  if (!Array.isArray(pageNames) || pageNames.includes(checkedTheme.slug)) {
    throw new Error(`the theme's slug "${checkedTheme.slug}" is already used by another page`);
  }
  if (typeof publicDir !== 'string' || publicDir === '') throw new Error('publicDir is required');

  const artPresent = checkArt(publicDir, checkedContent.days, checkedTheme.artRequired);

  const outputs = [];
  for (const entry of checkedContent.days) {
    const file = dayFile(entry, artPresent.includes(entry.art));
    validateDayFile(file, entry.day);
    outputs.push([`advent/day-${dayNumber(entry.day)}.json`, `${JSON.stringify(file, null, 2)}\n`]);
  }
  outputs.push(['css/advent-theme.css', themeCss(checkedTheme)]);
  outputs.push(...clientFiles());

  for (const [path, text] of outputs) writeIfChanged(join(publicDir, path), text);

  return {
    theme: checkedTheme,
    content: checkedContent,
    pageUrl: `${siteUrl}/${checkedTheme.slug}.html`,
    artPresent,
    files: outputs.map(([path]) => path),
    tokenContext: { theme: checkedTheme },
  };
}

// ---------------------------------------------------------------------------
// The page

function wholeNumber(value, where) {
  if (!Number.isInteger(value)) throw new Error(`season: ${where} must be a whole number`);
  return value;
}

/**
 * Replaces {{ADVENT}} with the calendar's markup: MARKUP ONLY, nothing from the days, no script,
 * no style attribute, no event handler. The page must supply its own h1; this adds h2s only.
 * Run it before the host adds heading ids. Pass ctx = buildAdvent(...).tokenContext.
 */
export function renderAdventToken(html, ctx) {
  if (!html.includes(TOKEN)) return html;
  const { theme } = ctx;
  const { start, end, archiveUntil } = theme.season;
  const startMonth = wholeNumber(start.month, 'start.month');
  const startDay = wholeNumber(start.day, 'start.day');
  const label = `${startDay} ${MONTH_NAMES[startMonth - 1]}`;
  const heading = escapeText(`${theme.siteName} Advent calendar`);
  const data = [
    ['data-advent', 'true'],
    ['data-slug', theme.slug],
    ['data-time-zone', theme.timeZone],
    ['data-start-month', startMonth],
    ['data-start-day', startDay],
    ['data-end-month', wholeNumber(end.month, 'end.month')],
    ['data-end-day', wholeNumber(end.day, 'end.day')],
    ...(archiveUntil
      ? [['data-archive-month', wholeNumber(archiveUntil.month, 'archiveUntil.month')], ['data-archive-day', wholeNumber(archiveUntil.day, 'archiveUntil.day')]]
      : []),
    ['data-preview', theme.previewEnabled === true],
    ['data-enabled', theme.adventEnabled === true],
    ['data-day-count', DAY_COUNT],
    ['data-month-name', MONTH_NAMES[startMonth - 1]],
    ['data-opens-text', `Advent opens on ${label}.`],
    ['data-again-text', `Advent comes round again on ${label}.`],
  ].map(([name, value]) => `${name}="${escapeText(value)}"`).join(' ');

  const markup = `<section class="advent" ${data}>
  <div class="advent-notice" data-advent-notice hidden>
    <p data-advent-notice-text></p>
  </div>
  <div class="advent-calm" data-advent-calm>
    <h2>${heading}</h2>
    <p data-advent-calm-text>${escapeText(`Advent opens on ${label}.`)}</p>
  </div>
  <div class="advent-live" data-advent-live hidden>
    <h2>${heading}</h2>
    <ul class="advent-doors" data-advent-doors></ul>
  </div>
  <noscript><p>The Advent calendar needs JavaScript to open its doors. Please switch JavaScript on and reload this page.</p></noscript>
</section>`;
  return html.split(TOKEN).join(markup);
}

/**
 * The calendar page's entry for the host's page list. While theme.publicListing is false the page
 * is unlisted (kept out of the sitemap and search) and carries noindex; flipping publicListing to
 * true lists it and drops the noindex, with no other change.
 */
export function adventPageEntry(theme) {
  const checked = validateTheme(theme);
  const name = escapeText(checked.siteName);
  const entry = {
    slug: checked.slug,
    title: `Advent — ${name}`,
    description: `The ${name} Advent calendar.`,
    active: null,
    header: true,
    safeguardStrip: false,
    headHtml: [
      '<link rel="stylesheet" href="/css/advent-theme.css">',
      '<link rel="stylesheet" href="/css/advent.css">',
      '<script type="module" src="/js/advent.js"></script>',
    ].join('\n'),
    unlisted: !checked.publicListing,
  };
  if (!checked.publicListing) entry.robots = 'noindex, nofollow';
  return entry;
}
