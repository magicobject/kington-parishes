// Build step for the Advent calendar. Generic: the host site passes everything in
// ({theme, content, publicDir, siteUrl, pageNames}) and this file never reads the
// host's own files. It may import only from this folder and from Node itself.
//
// What it does, in order, and nothing is written unless every check passes:
//   1. checks the theme and the content with the validators, and uses the COPIES they return
//   2. checks the pictures in <publicDir>/advent/art (see lintSvg, artFilePath)
//   3. writes, all from that checked data:
//        advent/day-01.json ... day-25.json   one plain-text file per day (validated again)
//        css/advent-theme.css                 the theme's colours as --advent-* variables
//        css/advent.css, js/advent.js         copied from client/ (hand-maintained)
//        js/advent/date.js, preview.js, day.js, logic.js   copies of date.mjs, preview.mjs, day.mjs and logic.mjs,
//                                             so the browser runs the very same date, day-rule and
//                                             helper code the tests do
//        js/advent-teaser.js, css/advent-teaser.css   the small home-page banner (loaded only on pages with the token)
//        advent/scene-default.svg             the module's plain hills scene, only when the theme names no scene of its own
// Every generated file starts with an AUTO-GENERATED banner (JSON cannot carry one) and is
// written the same way every time (stable key order, LF, one trailing newline), so a rebuild
// only changes a file when its source changed.
//
// Also exported for the host: renderAdventToken (the {{ADVENT}} markup), renderAdventTeaserToken (the
// {{ADVENT_TEASER}} home-page banner) and adventPageEntry (the page's entry for the host's page list).
